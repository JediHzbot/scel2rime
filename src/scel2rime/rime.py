"""Render parsed dictionaries as Rime `.dict.yaml` files.

The output is plain text assembled by hand: the tool has no third-party
dependencies, and Rime's dictionary grammar is a short fixed header followed by
tab-separated rows.

Row format (the default `text / code / weight` columns):

    <word>\t<syllable> <syllable> ...\t<weight>

Sogou stores a 1..10 usefulness grade, not a real frequency, so weights are
scaled by default to sit in the same range as hand-maintained Rime dictionaries
(which routinely use values up to 100000). Scaling only changes relative order
inside this dictionary, and `--scale 1` restores the raw grade.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

from .scel import ScelDictionary, WordEntry

DEFAULT_WEIGHT_SCALE = 100

# Rime derives the dictionary identity from the file name, so the id has to
# survive as a path component. Only path-hostile characters are replaced; CJK is
# kept, because a dictionary called `系统集成专用词库` is far easier to wire into a
# schema than `sogou_fbbeabd2`.
_NAME_UNSAFE = re.compile(r'[\\/:*?"<>|\x00-\x1f]+')
_WHITESPACE = re.compile(r"\s+")


def sanitize_name(candidate: str, fallback: str = "sogou_dict") -> str:
    """Turn an arbitrary dictionary name into a usable Rime dictionary id."""
    cleaned = _NAME_UNSAFE.sub("_", candidate.strip())
    cleaned = _WHITESPACE.sub("_", cleaned).strip("._ ")
    return cleaned or fallback


def name_for(dictionary: ScelDictionary, index: int = 0, override: str | None = None) -> str:
    """Pick a stable dictionary id for one parsed file.

    The dictionary's own name wins, then the file stem; a name that sanitises
    into nothing falls back to a short digest so batch runs never collide.
    """
    if override:
        return sanitize_name(override)
    for candidate in (dictionary.name, dictionary.path.stem):
        if not candidate:
            continue
        cleaned = sanitize_name(candidate, fallback="")
        if cleaned:
            return cleaned
    digest = hashlib.sha1(f"{dictionary.name}|{dictionary.path.name}".encode("utf-8")).hexdigest()[:8]
    return f"sogou_{digest}"


def dedupe(entries: list[WordEntry]) -> list[WordEntry]:
    """Collapse repeated (word, syllables) pairs, keeping the highest grade."""
    best: dict[tuple[str, tuple[str, ...]], WordEntry] = {}
    for entry in entries:
        key = (entry.word, entry.syllables)
        current = best.get(key)
        if current is None or entry.frequency > current.frequency:
            best[key] = entry
    return list(best.values())


def weight_for(entry: WordEntry, scale: int = DEFAULT_WEIGHT_SCALE) -> int:
    """Map Sogou's 1..10 grade onto a Rime weight."""
    grade = entry.frequency if entry.frequency > 0 else 1
    return grade * max(1, scale)


def render(
    dictionary: ScelDictionary,
    name: str,
    *,
    scale: int = DEFAULT_WEIGHT_SCALE,
    sort_by_weight: bool = True,
    source_note: str | None = None,
    extra_header: list[str] | None = None,
) -> str:
    """Render one dictionary as the full text of a `.dict.yaml` file."""
    entries = dedupe(dictionary.entries)
    if sort_by_weight:
        entries.sort(key=lambda item: (-weight_for(item, scale), item.word))

    lines: list[str] = [
        "# Rime dictionary",
        "# encoding: utf-8",
        "#",
        "# Generated by scel2rime from a dictionary you own.",
        "# Review the header fields below before enabling it in a schema:",
        "#   `import_tables` pulls this file into a schema; `sort` and",
        "#   `use_preset_vocabulary` control merge behaviour.",
    ]
    if source_note:
        lines.append(f"# source: {source_note}")
    lines.append(f"# entries: {len(entries)}")
    if dictionary.warnings:
        lines.append(f"# warnings: {len(dictionary.warnings)} (see `scel2rime info`)")
    if extra_header:
        lines.extend(f"# {line}" for line in extra_header)

    lines.extend(
        [
            "",
            "---",
            f"name: {name}",
            'version: "1"',
            f"sort: {'by_weight' if sort_by_weight else 'original'}",
            "use_preset_vocabulary: true",
            "columns:",
            "  - text",
            "  - code",
            "  - weight",
            "...",
            "",
        ]
    )

    for entry in entries:
        pinyin = " ".join(entry.syllables)
        lines.append(f"{entry.word}\t{pinyin}\t{weight_for(entry, scale)}")

    return "\n".join(lines) + "\n"


def write(
    dictionary: ScelDictionary,
    destination: Path,
    name: str,
    **options,
) -> Path:
    """Write one dictionary to `destination` and return the path."""
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(render(dictionary, name, **options), encoding="utf-8")
    return destination
